using Microsoft.EntityFrameworkCore;
using SchoolManagement.Models;
using SchoolManagement.Services;

namespace SchoolManagement.Data;

public static class DbInitializer
{
    public static async Task InitializeAsync(WebApplication app)
    {
        using var scope = app.Services.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        var passwordService = scope.ServiceProvider.GetRequiredService<IPasswordService>();

        // Creates every table/column directly from the current EF model. This only
        // takes effect on a brand-new, empty database (a no-op if one already exists).
        await context.Database.EnsureCreatedAsync();

        // EnsureCreated never alters an existing database, so columns added to the model
        // after the first deployment are applied here. Each statement is idempotent.
        await context.Database.ExecuteSqlRawAsync(
            "ALTER TABLE \"ExamQuestions\" ADD COLUMN IF NOT EXISTS \"QuestionType\" text NOT NULL DEFAULT 'MultipleChoice';");
        await context.Database.ExecuteSqlRawAsync(
            "ALTER TABLE \"ExamQuestions\" ADD COLUMN IF NOT EXISTS \"AttachmentPath\" text NULL;");

        // Per-question exam answers (written answers to uploaded questions are marked by the teacher).
        await context.Database.ExecuteSqlRawAsync(@"
            CREATE TABLE IF NOT EXISTS ""ExamAnswers"" (
                ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
                ""SchoolId"" integer NOT NULL,
                ""ExamSubmissionId"" integer NOT NULL,
                ""ExamQuestionId"" integer NOT NULL,
                ""AnswerText"" text NOT NULL,
                ""IsCorrect"" boolean NULL,
                CONSTRAINT ""PK_ExamAnswers"" PRIMARY KEY (""Id""),
                CONSTRAINT ""FK_ExamAnswers_ExamSubmissions_ExamSubmissionId"" FOREIGN KEY (""ExamSubmissionId"")
                    REFERENCES ""ExamSubmissions"" (""Id"") ON DELETE CASCADE,
                CONSTRAINT ""FK_ExamAnswers_ExamQuestions_ExamQuestionId"" FOREIGN KEY (""ExamQuestionId"")
                    REFERENCES ""ExamQuestions"" (""Id"") ON DELETE CASCADE
            );");
        await context.Database.ExecuteSqlRawAsync(
            "CREATE INDEX IF NOT EXISTS \"IX_ExamAnswers_ExamSubmissionId\" ON \"ExamAnswers\" (\"ExamSubmissionId\");");
        await context.Database.ExecuteSqlRawAsync(
            "CREATE INDEX IF NOT EXISTS \"IX_ExamAnswers_ExamQuestionId\" ON \"ExamAnswers\" (\"ExamQuestionId\");");

        // Assignments are given to a grade.
        await context.Database.ExecuteSqlRawAsync(
            "ALTER TABLE \"Assignments\" ADD COLUMN IF NOT EXISTS \"ClassId\" integer NULL;");
        await context.Database.ExecuteSqlRawAsync(
            "CREATE INDEX IF NOT EXISTS \"IX_Assignments_ClassId\" ON \"Assignments\" (\"ClassId\");");
        await context.Database.ExecuteSqlRawAsync(@"
            DO $$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Assignments_Classes_ClassId') THEN
                    ALTER TABLE ""Assignments"" ADD CONSTRAINT ""FK_Assignments_Classes_ClassId""
                        FOREIGN KEY (""ClassId"") REFERENCES ""Classes"" (""Id"") ON DELETE SET NULL;
                END IF;
            END $$;");

        await context.Database.ExecuteSqlRawAsync(
            "ALTER TABLE \"Exams\" ADD COLUMN IF NOT EXISTS \"DurationMinutes\" integer NULL;");
        await context.Database.ExecuteSqlRawAsync(
            "ALTER TABLE \"Exams\" ADD COLUMN IF NOT EXISTS \"ReminderSentAt\" timestamp without time zone NULL;");

        // Marks per question (teachers set them for uploaded questions) and the marks a
        // written answer was given.
        await context.Database.ExecuteSqlRawAsync(
            "ALTER TABLE \"ExamQuestions\" ADD COLUMN IF NOT EXISTS \"Marks\" integer NOT NULL DEFAULT 1;");
        await context.Database.ExecuteSqlRawAsync(
            "ALTER TABLE \"ExamAnswers\" ADD COLUMN IF NOT EXISTS \"MarksAwarded\" integer NULL;");
        await context.Database.ExecuteSqlRawAsync(
            "ALTER TABLE \"ExamSubmissions\" ADD COLUMN IF NOT EXISTS \"TotalMarks\" integer NULL;");

        // Seed a default school + its first Admin account, but only on a first-ever run.
        var defaultSchool = await context.Schools.FirstOrDefaultAsync(s => s.Slug == "heavens-gate-academy");
        if (defaultSchool == null)
        {
            defaultSchool = new School
            {
                Name = "Heavens Gate Academy",
                Slug = "heavens-gate-academy",
                IsActive = true
            };
            context.Schools.Add(defaultSchool);
            await context.SaveChangesAsync();
        }

        // Query filters are ignored here because no tenant is resolved at startup (no HTTP request yet).
        if (!context.Users.IgnoreQueryFilters().Any(u => u.Username == "admin" && u.SchoolId == defaultSchool.Id))
        {
            var adminUser = new User
            {
                SchoolId = defaultSchool.Id,
                Username = "admin",
                Email = "admin@schoolmanagement.com",
                FullName = "Administrator",
                PasswordHash = passwordService.HashPassword("admin123"),
                IsActive = true
            };

            context.Users.Add(adminUser);
            await context.SaveChangesAsync();

            var adminRole = context.Roles.FirstOrDefault(r => r.Name == "Admin");
            if (adminRole != null)
            {
                context.UserRoles.Add(new UserRole { UserId = adminUser.Id, RoleId = adminRole.Id });
                await context.SaveChangesAsync();
            }
        }
    }
}
